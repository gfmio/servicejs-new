console.log('Original data:', testData.length, 'bytes');
console.log('Hex:', Array.from(testData).map(b => b.toString(16).padStart(2, '0')).join(' '));
console.log('');

const packed = pack(testData);
console.log('Packed data:', packed.length, 'bytes');
console.log('Hex:', Array.from(packed).map(b => b.toString(16).padStart(2, '0')).join(' '));
console.log('');

try {
  const unpacked = unpack(packed);
  console.log('Unpacked data:', unpacked.length, 'bytes');
  console.log('Hex:', Array.from(unpacked).map(b => b.toString(16).padStart(2, '0')).join(' '));
  console.log('');

  const matches = testData.length === unpacked.length && testData.every((b, i) => b === unpacked[i]);
  console.log('Round-trip successful:', matches ? '✓' : '✗');

  if (!matches) {
    console.log('Differences:');
    for (let i = 0; i < Math.max(testData.length, unpacked.length); i++) {
      if (testData[i] !== unpacked[i]) {
        console.log(`  Byte ${i}: expected ${testData[i]?.toString(16) ?? 'missing'}, got ${unpacked[i]?.toString(16) ?? 'missing'}`);
      }
    }
  }
} catch (error) {
  console.log('Unpack failed:', error);
}
