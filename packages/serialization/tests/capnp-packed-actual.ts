// Exact packed bytes from the failing serializer
const actualPacked = new Uint8Array([
  0x10, 0x0d, 0x11, 0x2a, 0x01, 0x00, 0x07, 0xe0,
  0xe0, 0x58, 0x40, 0x11, 0x01, 0x52, 0xff, 0x54,
  0x65, 0x73, 0x74, 0x20, 0x55, 0x73, 0x65, 0x01,
  0x72,
]);

console.log('=== Test 1: Pack the unpacked data ===');
console.log('Unpacked data:', actualUnpacked.length, 'bytes');
const packed = pack(actualUnpacked);
console.log('Packed result:', packed.length, 'bytes');
console.log('Expected packed:', actualPacked.length, 'bytes');
console.log('');
console.log('Packed matches expected:', Array.from(packed).every((b, i) => b === actualPacked[i]) && packed.length === actualPacked.length ? '✓' : '✗');
if (packed.length !== actualPacked.length || !Array.from(packed).every((b, i) => b === actualPacked[i])) {
  console.log('Packed hex:  ', Array.from(packed).map(b => b.toString(16).padStart(2, '0')).join(' '));
  console.log('Expected hex:', Array.from(actualPacked).map(b => b.toString(16).padStart(2, '0')).join(' '));
}
console.log('');

console.log('=== Test 2: Unpack the packed data from serializer ===');
try {
  const unpacked = unpack(actualPacked);
  console.log('Unpacked result:', unpacked.length, 'bytes');
  console.log('Expected unpacked:', actualUnpacked.length, 'bytes');
  console.log('Unpacked matches expected:', Array.from(unpacked).every((b, i) => b === actualUnpacked[i]) && unpacked.length === actualUnpacked.length ? '✓' : '✗');
} catch (error) {
  console.log('Unpack failed:', error);
}
